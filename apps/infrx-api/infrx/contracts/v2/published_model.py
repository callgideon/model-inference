"""F2C.c — the published-model projection: public capability and accounting identity.

One record answers "what may a caller send to this model, how is it priced, what does
serving keep" for every consumer of that answer: the discovery route and any provider
document (G7), the console catalog/docs (A3), the pricing seam (D10) and the dataset
client (E1C). RV-01 is the defect this closes: `/v1/models` returned a static file that
advertised 120 s videos, tool parameters, a readiness flag and zero data retention, none
of which the runtime honours. The TypeScript twin is
`apps/app/lib/contracts/v2/published-model.ts`; both halves serialize a record to the same
canonical bytes (`codec.canonical_bytes`) and read the same fixtures from `published/`
(generated by `published_fixtures.py`).

Rules this module is the single statement of (proposed ruling R109):

* **Resolution is defined once.** `split_model` is the grammar `<public id>[@<revision
  label>]` (0008 `resolve_admission_pins`'s own pattern) and `resolve` picks, among the
  published records, the one with that id and label; an unlabelled id takes the highest
  listing. Nothing resolves by a spelling it was not published under: the engine's served
  name `marlin2b`, the artifact repo `NemoStation/Marlin-2B` and a coming-soon row are
  `not_found`.
* **Pricing follows resolution, never the spelling (P-22).** `price` returns the pins an
  admission records: the caller's `requested_model` verbatim beside the canonical
  `model_revision`, deployment and serving revision, and exactly one price identity - the
  CREDIT `rate_card_version` in the credit regime, the USD `price_version` keyed by the
  canonical revision in the legacy regime. There is no conversion between the two and no
  function here produces one.
* **One public rate identity per revision.** It is `(rate_card_version, CREDIT)` of the
  card the revision's effective catalog listing names - the card 0008
  `resolve_admission_pins` pins - and `project` must be handed exactly that card. A card
  no effective listing names is not a public rate: `marlin_release()`'s locally computed
  `rc_marlin2b_<ts>_provisional_p01` (certify, endpoint_doc) was never written to the
  hosted catalog, whose listing names the seed's `rc_marlin2b_2026_09_provisional`. History
  maps through each job's own pinned `rate_card_version` (R78), never through the current
  identity: no mapping table, no rewritten row.
* **Unpriced or unpublishable fails closed.** `project` refuses a private or non-active
  deployment (`not_found`, R70) and a deployment without the active regime's price
  identity (`invalid_request`, R69). `Pricing` cannot be constructed without it either.
* **Availability is not capability.** `availability` says whether requests are being
  accepted now; `capability` says what an accepted request may contain. Neither implies
  the other, and no capacity or latency number is published (P-18: unmeasured).
* **A projection never advertises what serving refuses.** `violations` compares a
  projection with the `ServingProfile` the running deployment actually enforces: a cap may
  be advertised at or below the enforced one, a vocabulary only as a subset, the declared
  preprocessing constraints and every retention figure exactly.
* **Serving keeps content.** `ServingRetention` cannot state zero data retention or that
  turning trace capture off deletes serving content: payloads, media and results have
  their own lifecycles (RV-01, RV-03, P-25).
"""
