def test_the_g6b_minted_card_is_not_the_seeded_deployment_s_public_rate():
    """S3 F11. Oracle: `marlin_release()`'s locally computed provisional card (certify's
    `published_release`, the E4B endpoint doc) shown as the rate of the deployment the hosted
    catalog lists. It prices G6B's own deployment revision, so `project` refuses the pairing;
    the public identity is the listing's card, the seed's."""
    from infrx.operations import service
    _serving_g6b, deployment_g6b, card_g6b, requested = service.marlin_release(
        provider_org_id=v2fix.IDS.provider_org, created_at=v2fix.T0, effective_at=v2fix.T0)
    assert requested == v2fix.REQUESTED_MODEL
    assert card_g6b.rate_card_version == "rc_marlin2b_20260901T000000Z_provisional_p01"
    assert card_g6b.deployment_revision_id != _deployment().deployment_revision_id
    with pytest.raises(errors.InvalidRequest):
        _project(credit_card=card_g6b)
    published = pm.PublishedModel.model_validate(CREDIT_DOC)
    assert (published.pricing.credit.rate_card_version, published.pricing.credit.unit) == (
        v2fix.RATE_CARD_VERSION, "CREDIT")
    assert published.pricing.credit.provisional is True
