def _second_revision(label: str, listing_version: int) -> pm.PublishedModel:
    base = pm.PublishedModel.model_validate(CREDIT_DOC)
    serving = base.serving.model_copy(update={"revision_label": label})
    revision = f"{base.id}@{label}"
    usd = base.pricing.legacy_usd.model_copy(update={"model_revision": revision})
    return pm.PublishedModel.model_validate(
        {**CREDIT_DOC, "model_revision": revision, "listing_version": listing_version,
         "aliases": sorted({base.id, revision}), "serving": serving.model_dump(mode="json"),
         "pricing": {**CREDIT_DOC["pricing"], "legacy_usd": usd.model_dump(mode="json")}})


def test_the_unlabelled_id_takes_the_highest_listing_and_a_pin_its_own_revision():
    """Oracle: an alias that floats to an older listing, or a pin that floats at all
    (0008 `order by version desc`)."""
    old = pm.PublishedModel.model_validate(CREDIT_DOC)
    new = _second_revision("2026-10-01", 2)
    old_pinned = old.model_copy(update={"aliases": (old.model_revision,)})
    assert pm.resolve("nemostation/marlin-2b", [old_pinned, new]) is new
    assert pm.resolve(v2fix.REQUESTED_MODEL, [old_pinned, new]) is old_pinned
    assert pm.catalog_problems([old_pinned, new]) == []
    # the floating id advertised on the older record resolves elsewhere: a catalog problem
    assert pm.catalog_problems([old, new]) == [
        "nemostation/marlin-2b@2026-09-01: alias 'nemostation/marlin-2b' resolves to "
        "nemostation/marlin-2b@2026-10-01"]
    assert pm.catalog_problems([old, old]) != []


def test_pricing_preserves_the_requested_string_beside_the_canonical_revision():
    """Oracle: the requested spelling lost, or replaced by the canonical one, on the pin."""
    credit = pm.PublishedModel.model_validate(CREDIT_DOC)
    pin = pm.price("nemostation/marlin-2b", [credit])
    assert (pin.requested_model, pin.model_revision) == ("nemostation/marlin-2b",
                                                          v2fix.REQUESTED_MODEL)
    assert (pin.rate_card_version, pin.price_version) == (v2fix.RATE_CARD_VERSION, None)
    legacy = pm.price("nemostation/marlin-2b", [pm.PublishedModel.model_validate(LEGACY_DOC)])
    assert (legacy.rate_card_version, legacy.price_version) == (
        None, "pv_marlin2b_usd_2026_09_r1")


def test_the_two_price_identities_never_convert():
    """Oracle: a CREDIT rate derived from USD (or the reverse): the units are distinct
    types, and a pin carrying both identities, or neither, does not construct."""
    credit = pm.PublishedModel.model_validate(CREDIT_DOC).pricing
    assert isinstance(credit.credit.input_rate_per_million, Credit)
    assert isinstance(credit.legacy_usd.input_rate_per_million, Usd)
    with pytest.raises(TypeError):
        credit.credit.input_rate_per_million + credit.legacy_usd.input_rate_per_million
    pin = pm.price(v2fix.REQUESTED_MODEL, [pm.PublishedModel.model_validate(CREDIT_DOC)])
    for update in ({"price_version": "pv_x"}, {"rate_card_version": None}):
        with pytest.raises(ValidationError):
            pm.PricedResolution.model_validate({**pin.model_dump(mode="json"), **update})


# --- P-22: every existing alias, before and after -------------------------------
ROWS = {row["price_version"]: row for row in ALIASES["hosted_usd_rows"]}


@pytest.mark.parametrize("case", ALIASES["cases"], ids=lambda c: c["requested"])
def test_no_historical_resolution_or_price_changes(case):
    """Oracle: an alias that resolved (or was refused) on the pilot resolving differently,
    or pricing at other rates, under the resolve-then-price rule. `before` is the recorded
    outcome on the hosted pilot at bda1586, where the USD lookup keyed the literal string."""
    before = case["before"]
    for regime in ("credit", "legacy_usd"):
        after = case[regime]
        assert after == pf._priced(case["requested"], pm.PublishedModel.model_validate(
            CREDIT_DOC if regime == "credit" else LEGACY_DOC))
        if "refused" in before:
            assert after == before, f"{case['requested']} is newly resolvable in {regime}"
            continue
        assert after["deployment_revision_id"] == before["deployment_revision_id"]
        assert after["requested_model"] == case["requested"]
        assert after["model_revision"] == v2fix.REQUESTED_MODEL
    if "refused" not in before:
        # the literal lookup keyed this very spelling; the canonical row prices the same
        old, new = ROWS[before["price_version"]], ROWS[case["legacy_usd"]["price_version"]]
        assert old["model_revision"] == case["requested"]
        assert new["model_revision"] == v2fix.REQUESTED_MODEL
        for field in ("input_rate_per_million", "output_rate_per_million",
                      "token_rules_version"):
            assert new[field] == old[field]


def _model_strings_in(paths: list[str]) -> set[str]:
    pattern = re.compile(r'"(?:model|model_revision|requested_model)":\s*"([^"]+)"')
    return {m for path in paths for m in pattern.findall((REPO / path).read_text())}


def test_the_table_covers_every_model_string_in_fixtures_and_results():
    """Oracle: a client, fixture or result spelling nobody checked for compatibility."""
    tracked = subprocess.run(["git", "ls-files", "models/marlin2b/results",
                              "apps/infrx-api/infrx/contracts/fixtures",
                              "apps/app/lib/contracts/fixtures"],
                             cwd=REPO, capture_output=True, text=True, check=True).stdout.split()
    seen = _model_strings_in([p for p in tracked if p.endswith((".json", ".jsonl"))])
    seen |= _model_strings_in(["research/plan/evidence/e/E4B-endpoint.md"])
    seed = (REPO / "apps/app/supabase/migrations/0002_seed_models.sql").read_text()
    seen |= set(re.findall(r"^\s*\('([^']+)', '[^']+', '[^']+',$", seed, re.M))
    seen.add(config.Settings().model_id)
    tabled = {case["requested"] for case in ALIASES["cases"]}
    assert seen, "found no model strings: the scan is broken"
    assert seen - {"claude-opus-5"} <= tabled, sorted(seen - tabled)


