def _serving():
    return v2fix.BUILDERS["serving_revision.json"]()


def _deployment():
    return v2fix.BUILDERS["deployment_revision_public.json"]()


def _project(**overrides):
    profile = pf.deployed_profile()
    kw = dict(serving=_serving(), deployment=_deployment(), listing_version=1,
              regime="credit", credit_card=v2fix.BUILDERS["rate_card_marlin.json"](),
              credit_provisional=True, usd_price=pf._canonical_usd_row(),
              capability=profile.capability, retention=profile.retention, owned_by="nemostation",
              available=True, as_of=pf.AS_OF)
    kw.update(overrides)
    return pm.project(**kw)


# --- fixtures: generated, fresh, identical bytes ------------------------------
def test_every_fixture_is_claimed_and_fresh():
    """Oracle: a record change nobody regenerated, or a stray hand-written file."""
    assert set(pf.names()) == set(pf.BUILDERS)
    built = pf.build()
    for name in pf.names():
        assert built[name] == (pf.DIR / name).read_bytes(), (
            f"{name} is stale: uv run --frozen python -m infrx.contracts.v2.published_fixtures "
            f"--write")


@pytest.mark.parametrize("name,model", [("published_marlin_credit.json", pm.PublishedModel),
                                        ("published_marlin_legacy_usd.json", pm.PublishedModel),
                                        ("serving_profile_marlin.json", pm.ServingProfile)])
def test_each_record_round_trips_to_identical_bytes(name, model):
    """Oracle: a field that serializes differently from how it parses (the TS half
    byte-compares its own re-serialization against the same file)."""
    raw = (pf.DIR / name).read_bytes()
    assert codec.canonical_bytes(model.model_validate(json.loads(raw))) == raw


# --- the deployed profile is the runtime's, not a transcription ----------------
def runtime_profile(env: dict[str, str]) -> pm.ServingProfile:
    """How G7 builds the enforced profile from the running configuration (reference)."""
    settings = config.from_env(env)
    return pm.serving_profile(
        limits=settings.pilot, deployment=_deployment(), serving=_serving(),
        parameters=validate.SUPPORTED, refused=validate.UNSUPPORTED,
        video_mime=set(settings.allowed_video_mime) & set(MediaProfile().allowed_mime),
        fps=int(settings.fps), min_frames=settings.min_frames, max_frames=settings.max_frames,
        max_pixels_per_frame=settings.px_per_frame, execution_modes=list(v1.ExecutionMode))


def test_the_fixture_profile_is_what_the_deployed_configuration_enforces():
    """Oracle: the fixture's allow-list, MIME set, sampling or TTLs drifting from the code
    (validate.SUPPORTED/UNSUPPORTED, MediaProfile, Settings) or from the 82 s env."""
    assert runtime_profile({"MAX_VIDEO_SECONDS": "82"}) == PROFILE
    assert set(pf.ACCEPTED_PARAMETERS) == validate.SUPPORTED
    assert set(pf.REFUSED_PARAMETERS) == validate.UNSUPPORTED


def test_the_code_default_120s_profile_is_not_the_deployed_one():
    """Oracle: publishing from code defaults. Without MAX_VIDEO_SECONDS=82 the runtime
    enforces 120 s, so a projection built from the defaults advertises what the pilot
    refuses (P-20)."""
    default = runtime_profile({})
    assert default.capability.video.max_seconds == 120
    published = pm.PublishedModel.model_validate(CREDIT_DOC)
    assert pm.violations(published, default) == []            # honest against 120 s
    stale = published.model_copy(update={"capability": default.capability})
    assert [v.split(":")[0] for v in pm.violations(stale, PROFILE)] == [
        "capability.video.max_seconds"]


def test_the_profile_follows_the_deployment_ceilings():
    """Oracle: advertising the pilot's 32k context when the deployment validated less."""
    small = _deployment().model_copy(update={"max_input_tokens": 20000,
                                             "max_output_tokens": 1024})
    profile = pm.serving_profile(limits=pf.DEPLOYED_LIMITS, deployment=small, serving=_serving(),
                                 parameters=pf.ACCEPTED_PARAMETERS, refused=pf.REFUSED_PARAMETERS,
                                 video_mime=pf.SERVED_VIDEO_MIME, execution_modes=pf.MODES,
                                 **pf.VIDEO_SAMPLING)
    assert (profile.capability.max_input_tokens, profile.capability.max_output_tokens) == (
        20000, 1024)


